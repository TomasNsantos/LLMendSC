"""
Sistema de Relatórios para SmartGuard
Gera relatórios detalhados sobre correções de vulnerabilidades
"""

import json
import time
import os
from datetime import datetime
from typing import Dict, List, Optional
from dataclasses import dataclass, asdict
import numpy as np
import matplotlib.pyplot as plt
import seaborn as sns
from pathlib import Path

@dataclass
class ContractAnalysis:
    """Dados de análise de um contrato"""
    filename: str
    original_vulnerabilities: List[str]
    correction_successful: bool
    final_security_score: float
    iterations_needed: int
    processing_time: float
    api_calls_made: int
    correction_history: List[Dict]
    timestamp: str

@dataclass
class BatchReport:
    """Relatório de processamento em lote"""
    total_contracts: int
    successful_corrections: int
    failed_corrections: int
    success_rate: float
    avg_iterations: float
    avg_security_score: float
    avg_processing_time: float
    vulnerability_distribution: Dict[str, int]
    performance_metrics: Dict[str, float]

class SmartGuardReporter:
    """
    Sistema de relatórios avançado para SmartGuard
    """
    
    def __init__(self, reports_dir: str = "correction_reports"):
        self.reports_dir = Path(reports_dir)
        self.reports_dir.mkdir(exist_ok=True)
        self.contract_analyses: List[ContractAnalysis] = []
        
    def add_contract_analysis(self, analysis: ContractAnalysis):
        """Adiciona análise de contrato ao relatório"""
        self.contract_analyses.append(analysis)
    
    def generate_individual_report(self, analysis: ContractAnalysis) -> str:
        """
        Gera relatório individual detalhado para um contrato
        """
        report_content = f"""
# SmartGuard Vulnerability Correction Report

## Contract Information
- **File**: {analysis.filename}
- **Timestamp**: {analysis.timestamp}
- **Processing Time**: {analysis.processing_time:.2f} seconds
- **API Calls Made**: {analysis.api_calls_made}

## Vulnerability Analysis
- **Original Vulnerabilities Found**: {len(analysis.original_vulnerabilities)}
  {self._format_vulnerability_list(analysis.original_vulnerabilities)}

## Correction Process
- **Correction Successful**: {'✅ Yes' if analysis.correction_successful else '❌ No'}
- **Iterations Needed**: {analysis.iterations_needed}
- **Final Security Score**: {analysis.final_security_score:.2f}/1.0

## Correction History
{self._format_correction_history(analysis.correction_history)}

## Security Assessment
{self._generate_security_assessment(analysis)}

---
Generated by SmartGuard v1.0 - {datetime.now().strftime('%Y-%m-%d %H:%M:%S')}
"""
        
        # Save individual report
        report_path = self.reports_dir / f"{analysis.filename}_report.md"
        with open(report_path, 'w', encoding='utf-8') as f:
            f.write(report_content)
        
        return str(report_path)
    
    def generate_batch_report(self) -> BatchReport:
        """
        Gera relatório consolidado de todos os contratos processados
        """
        if not self.contract_analyses:
            return BatchReport(
                total_contracts=0, successful_corrections=0, failed_corrections=0,
                success_rate=0.0, avg_iterations=0.0, avg_security_score=0.0,
                avg_processing_time=0.0, vulnerability_distribution={},
                performance_metrics={}
            )
        
        total_contracts = len(self.contract_analyses)
        successful = sum(1 for a in self.contract_analyses if a.correction_successful)
        failed = total_contracts - successful
        
        success_rate = successful / total_contracts if total_contracts > 0 else 0.0
        
        avg_iterations = np.mean([a.iterations_needed for a in self.contract_analyses])
        avg_security_score = np.mean([a.final_security_score for a in self.contract_analyses])
        avg_processing_time = np.mean([a.processing_time for a in self.contract_analyses])
        
        # Distribuição de vulnerabilidades
        vuln_dist = {}
        for analysis in self.contract_analyses:
            for vuln in analysis.original_vulnerabilities:
                vuln_dist[vuln] = vuln_dist.get(vuln, 0) + 1
        
        # Métricas de performance
        successful_analyses = [a for a in self.contract_analyses if a.correction_successful]
        performance_metrics = {
            'success_rate': success_rate,
            'avg_iterations_successful': np.mean([a.iterations_needed for a in successful_analyses]) if successful_analyses else 0,
            'avg_security_score_successful': np.mean([a.final_security_score for a in successful_analyses]) if successful_analyses else 0,
            'total_api_calls': sum(a.api_calls_made for a in self.contract_analyses),
            'total_processing_time': sum(a.processing_time for a in self.contract_analyses)
        }
        
        batch_report = BatchReport(
            total_contracts=total_contracts,
            successful_corrections=successful,
            failed_corrections=failed,
            success_rate=success_rate,
            avg_iterations=avg_iterations,
            avg_security_score=avg_security_score,
            avg_processing_time=avg_processing_time,
            vulnerability_distribution=vuln_dist,
            performance_metrics=performance_metrics
        )
        
        # Save batch report
        self._save_batch_report(batch_report)
        
        return batch_report
    
    def generate_visualizations(self) -> List[str]:
        """
        Gera visualizações dos dados de correção
        """
        if not self.contract_analyses:
            return []
        
        plt.style.use('seaborn-v0_8')
        generated_plots = []
        
        # 1. Success Rate Chart
        success_chart_path = self._create_success_rate_chart()
        if success_chart_path:
            generated_plots.append(success_chart_path)
        
        # 2. Vulnerability Distribution
        vuln_chart_path = self._create_vulnerability_distribution_chart()
        if vuln_chart_path:
            generated_plots.append(vuln_chart_path)
        
        # 3. Security Score Distribution
        security_chart_path = self._create_security_score_distribution()
        if security_chart_path:
            generated_plots.append(security_chart_path)
        
        # 4. Iterations vs Success
        iterations_chart_path = self._create_iterations_analysis()
        if iterations_chart_path:
            generated_plots.append(iterations_chart_path)
        
        return generated_plots
    
    def _format_vulnerability_list(self, vulnerabilities: List[str]) -> str:
        """Formata lista de vulnerabilidades"""
        if not vulnerabilities:
            return "  - None detected"
        
        return "\n".join([f"  - {vuln}" for vuln in vulnerabilities])
    
    def _format_correction_history(self, history: List[Dict]) -> str:
        """Formata histórico de correção"""
        if not history:
            return "No correction history available."
        
        formatted = []
        for i, entry in enumerate(history, 1):
            quality = entry.get('quality_score', 0.0)
            remaining = entry.get('remaining_vulnerabilities', [])
            successful = entry.get('successful', False)
            
            formatted.append(f"""
### Iteration {i}
- **Quality Score**: {quality:.2f}
- **Status**: {'✅ Successful' if successful else '⚠️ Needs improvement'}
- **Remaining Vulnerabilities**: {len(remaining)} ({', '.join(remaining) if remaining else 'None'})
""")
        
        return "\n".join(formatted)
    
    def _generate_security_assessment(self, analysis: ContractAnalysis) -> str:
        """Gera avaliação de segurança"""
        score = analysis.final_security_score
        
        if score >= 0.9:
            assessment = "🟢 **EXCELLENT** - Contract meets high security standards"
        elif score >= 0.8:
            assessment = "🟡 **GOOD** - Contract has good security with minor concerns"
        elif score >= 0.6:
            assessment = "🟠 **MODERATE** - Contract has security issues that should be addressed"
        else:
            assessment = "🔴 **POOR** - Contract has significant security vulnerabilities"
        
        recommendations = []
        if not analysis.correction_successful:
            recommendations.append("- Manual security review recommended")
            recommendations.append("- Consider additional static analysis tools")
        
        if analysis.iterations_needed > 3:
            recommendations.append("- Complex vulnerabilities detected - thorough testing advised")
        
        rec_text = "\n".join(recommendations) if recommendations else "- No additional recommendations"
        
        return f"""
{assessment}

**Recommendations:**
{rec_text}
"""
    
    def _save_batch_report(self, report: BatchReport):
        """Salva relatório em lote"""
        # JSON report
        json_path = self.reports_dir / f"batch_report_{datetime.now().strftime('%Y%m%d_%H%M%S')}.json"
        with open(json_path, 'w', encoding='utf-8') as f:
            json.dump(asdict(report), f, indent=2, ensure_ascii=False)
        
        # Markdown report
        md_content = f"""
# SmartGuard Batch Processing Report

**Generated**: {datetime.now().strftime('%Y-%m-%d %H:%M:%S')}

## Summary
- **Total Contracts Processed**: {report.total_contracts}
- **Successful Corrections**: {report.successful_corrections}
- **Failed Corrections**: {report.failed_corrections}
- **Success Rate**: {report.success_rate:.2%}

## Performance Metrics
- **Average Iterations**: {report.avg_iterations:.1f}
- **Average Security Score**: {report.avg_security_score:.2f}
- **Average Processing Time**: {report.avg_processing_time:.2f}s
- **Total API Calls**: {report.performance_metrics.get('total_api_calls', 0)}

## Vulnerability Distribution
{self._format_vulnerability_distribution(report.vulnerability_distribution)}

## Detailed Performance Analysis
- **Success Rate**: {report.performance_metrics.get('success_rate', 0):.2%}
- **Avg Iterations (Successful)**: {report.performance_metrics.get('avg_iterations_successful', 0):.1f}
- **Avg Security Score (Successful)**: {report.performance_metrics.get('avg_security_score_successful', 0):.2f}
- **Total Processing Time**: {report.performance_metrics.get('total_processing_time', 0):.2f}s
"""
        
        md_path = self.reports_dir / f"batch_report_{datetime.now().strftime('%Y%m%d_%H%M%S')}.md"
        with open(md_path, 'w', encoding='utf-8') as f:
            f.write(md_content)
    
    def _format_vulnerability_distribution(self, distribution: Dict[str, int]) -> str:
        """Formata distribuição de vulnerabilidades"""
        if not distribution:
            return "No vulnerabilities detected."
        
        sorted_vulns = sorted(distribution.items(), key=lambda x: x[1], reverse=True)
        total = sum(distribution.values())
        
        formatted = []
        for vuln, count in sorted_vulns:
            percentage = (count / total) * 100
            formatted.append(f"- **{vuln}**: {count} ({percentage:.1f}%)")
        
        return "\n".join(formatted)
    
    def _create_success_rate_chart(self) -> Optional[str]:
        """Cria gráfico de taxa de sucesso"""
        try:
            successful = sum(1 for a in self.contract_analyses if a.correction_successful)
            failed = len(self.contract_analyses) - successful
            
            plt.figure(figsize=(8, 6))
            labels = ['Successful', 'Failed']
            sizes = [successful, failed]
            colors = ['#2ecc71', '#e74c3c']
            
            plt.pie(sizes, labels=labels, colors=colors, autopct='%1.1f%%', startangle=90)
            plt.title('SmartGuard Correction Success Rate', fontsize=14, fontweight='bold')
            
            chart_path = self.reports_dir / 'success_rate_chart.png'
            plt.savefig(chart_path, dpi=300, bbox_inches='tight')
            plt.close()
            
            return str(chart_path)
        except Exception as e:
            print(f"Error creating success rate chart: {e}")
            return None
    
    def _create_vulnerability_distribution_chart(self) -> Optional[str]:
        """Cria gráfico de distribuição de vulnerabilidades"""
        try:
            vuln_dist = {}
            for analysis in self.contract_analyses:
                for vuln in analysis.original_vulnerabilities:
                    vuln_dist[vuln] = vuln_dist.get(vuln, 0) + 1
            
            if not vuln_dist:
                return None
            
            plt.figure(figsize=(12, 6))
            vulns = list(vuln_dist.keys())
            counts = list(vuln_dist.values())
            
            plt.bar(vulns, counts, color='#3498db', alpha=0.7)
            plt.title('Vulnerability Type Distribution', fontsize=14, fontweight='bold')
            plt.xlabel('Vulnerability Type')
            plt.ylabel('Count')
            plt.xticks(rotation=45, ha='right')
            
            chart_path = self.reports_dir / 'vulnerability_distribution.png'
            plt.savefig(chart_path, dpi=300, bbox_inches='tight')
            plt.close()
            
            return str(chart_path)
        except Exception as e:
            print(f"Error creating vulnerability distribution chart: {e}")
            return None
    
    def _create_security_score_distribution(self) -> Optional[str]:
        """Cria gráfico de distribuição de scores de segurança"""
        try:
            scores = [a.final_security_score for a in self.contract_analyses]
            
            plt.figure(figsize=(10, 6))
            plt.hist(scores, bins=20, color='#9b59b6', alpha=0.7, edgecolor='black')
            plt.title('Final Security Score Distribution', fontsize=14, fontweight='bold')
            plt.xlabel('Security Score')
            plt.ylabel('Frequency')
            plt.axvline(np.mean(scores), color='red', linestyle='--', label=f'Mean: {np.mean(scores):.2f}')
            plt.legend()
            
            chart_path = self.reports_dir / 'security_score_distribution.png'
            plt.savefig(chart_path, dpi=300, bbox_inches='tight')
            plt.close()
            
            return str(chart_path)
        except Exception as e:
            print(f"Error creating security score distribution chart: {e}")
            return None
    
    def _create_iterations_analysis(self) -> Optional[str]:
        """Cria gráfico de análise de iterações"""
        try:
            successful = [a for a in self.contract_analyses if a.correction_successful]
            failed = [a for a in self.contract_analyses if not a.correction_successful]
            
            plt.figure(figsize=(10, 6))
            
            if successful:
                plt.scatter([a.iterations_needed for a in successful], 
                           [a.final_security_score for a in successful], 
                           c='green', alpha=0.6, label='Successful', s=60)
            
            if failed:
                plt.scatter([a.iterations_needed for a in failed], 
                           [a.final_security_score for a in failed], 
                           c='red', alpha=0.6, label='Failed', s=60)
            
            plt.title('Iterations vs Security Score', fontsize=14, fontweight='bold')
            plt.xlabel('Iterations Needed')
            plt.ylabel('Final Security Score')
            plt.legend()
            plt.grid(True, alpha=0.3)
            
            chart_path = self.reports_dir / 'iterations_analysis.png'
            plt.savefig(chart_path, dpi=300, bbox_inches='tight')
            plt.close()
            
            return str(chart_path)
        except Exception as e:
            print(f"Error creating iterations analysis chart: {e}")
            return None